        'VERSION:3.0',
        'N:Giessenburg;Daniel;;;',
        'FN:Daniel Giessenburg',
        'ORG:Noppa B.V.',
        'TITLE:Consultant',
        'EMAIL;TYPE=WORK:daniel@noppa.nl',
        'TEL;TYPE=WORK,VOICE:+31 6 00 00 00 00',
        'URL:#',
        'ADR;TYPE=WORK:;;Parallelweg 27 (HA 0.03);\'s-Hertogenbosch;;5223 AL;Nederland',
        'END:VCARD'
    ].join('\r\n');
    const blob = new Blob([vcard], { type: 'text/vcard;charset=utf-8' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = 'daniel-giessenburg.vcf';
    document.body.appendChild(a);
    a.click();
    document.body.removeChild(a);
    URL.revokeObjectURL(url);
}
